import streamlit as st

st.title("🧾 Présentation du projet")

st.markdown("""
Le projet **BrainScan** a pour but de développer une application d’aide au diagnostic médical.  
À partir d’images IRM du cerveau, un modèle de Deep Learning identifie automatiquement le **type de tumeur cérébrale**.

### 🎯 Objectifs :
- Automatiser la détection des tumeurs à partir d’images IRM.
- Réduire les erreurs humaines dans l’interprétation médicale.
- Fournir un outil d’aide à la décision pour les professionnels de santé.

### 🧩 Technologies utilisées :
- Python 🐍  
- TensorFlow / Keras  
- OpenCV  
- Streamlit  
- NumPy, Matplotlib, scikit-learn  
""")
